import { readFileSync, writeFileSync } from 'node:fs';
import { createHmac, createPublicKey, verify, createHash, randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';

const api = 'https://stowgui-license-sandbox.trainvent.workers.dev';
const directory = 'worker/.wrangler/sandbox';
const secrets = JSON.parse(readFileSync(`${directory}/secrets.json`, 'utf8'));
const state = JSON.parse(readFileSync(`${directory}/credentials.json`, 'utf8'));
const checkout = JSON.parse(readFileSync(`${directory}/checkout.json`, 'utf8'));
const manifest = JSON.parse(readFileSync('worker/src/legal/manifest.json', 'utf8'));
const health = await (await fetch(`${api}/health`)).json();
assert.equal(health.environment, 'sandbox');
assert.equal(health.email, 'capture');
assert.equal(checkout.livemode, false);
const site = await fetch(`${api}/de/`);
assert.equal(site.status, 200);
assert.ok(site.headers.get('x-robots-tag').includes('noindex'));
const html = await site.text();
assert.ok(html.includes(checkout.url) && html.includes('Testpostfach'));
assert.equal((await fetch(`${api}/sandbox/mail`)).status, 401);
const login = await fetch(`${api}/sandbox/login`, { method: 'POST', headers: { Origin: api, 'Content-Type': 'application/json' }, body: JSON.stringify({ token: secrets.SANDBOX_INBOX_TOKEN }) });
assert.equal(login.status, 204);
const cookie = login.headers.get('set-cookie').split(';')[0];
const inbox = async () => (await fetch(`${api}/sandbox/mail`, { headers: { Cookie: cookie } })).json();
async function event(type, object, live = false) {
  const raw = JSON.stringify({ id: `evt_hosted_${randomUUID()}`, type, livemode: live, data: { object } });
  const timestamp = Math.floor(Date.now() / 1000);
  const signature = createHmac('sha256', secrets.STRIPE_WEBHOOK_SECRET).update(`${timestamp}.${raw}`).digest('hex');
  return fetch(`${api}/stripe/webhook`, { method: 'POST', headers: { 'Stripe-Signature': `t=${timestamp},v1=${signature}` }, body: raw });
}
const before = await inbox();
for (const message of before.filter(m => m.to.includes('deployment-check@example.invalid'))) {
  const reference = message.text.match(/cs_test_hosted_[a-z0-9_-]+/i)?.[0];
  if (reference) await event('charge.refunded', { payment_intent: reference.replace('cs_test_', 'pi_'), refunded: true });
}
const nonce = randomUUID();
const first = { id: `cs_test_hosted_${nonce}`, payment_link: checkout.payment_link, payment_status: 'paid', amount_total: 500, currency: 'eur', payment_intent: `pi_hosted_${nonce}`, locale: 'de', customer_details: { email: 'deployment-check@example.invalid', address: { country: 'DE' } } };
assert.equal((await event('checkout.session.completed', first, true)).status, 400);
assert.equal((await event('checkout.session.completed', first)).status, 200);
assert.equal((await event('checkout.session.completed', first)).status, 200);
const second = { ...first, id: `${first.id}_refund`, payment_intent: `${first.payment_intent}_refund`, locale: 'en', customer_details: { email: 'deployment-check@example.invalid', address: { country: 'US' } } };
assert.equal((await event('checkout.session.completed', second)).status, 200);
let messages = await inbox();
assert.equal(messages.length, Math.min(30, before.length + 2));
const current = messages.filter(m => m.text.includes(first.id));
const mail = current.find(m => !m.text.includes(second.id));
const keyFrom = m => m.text.match(/[A-Za-z0-9_-]{30,}\.[A-Za-z0-9_-]{60,}/)[0];
const key = keyFrom(mail);
const [encoded, signature] = key.split('.');
const payload = JSON.parse(Buffer.from(encoded, 'base64url').toString());
const publicKey = createPublicKey({ key: { kty: 'OKP', crv: 'Ed25519', x: state.publicKey }, format: 'jwk' });
assert.ok(verify(null, Buffer.from(encoded), publicKey, Buffer.from(signature, 'base64url')));
for (const message of current) for (let index = 0; index < message.attachments.length; index++) {
  const response = await fetch(`${api}/sandbox/mail/${message.id}/attachment/${index}`, { headers: { Cookie: cookie } });
  assert.equal(response.status, 200);
  assert.equal(createHash('sha256').update(Buffer.from(await response.arrayBuffer())).digest('hex'), manifest.pdfs[message.attachments[index]]);
}
assert.equal((await fetch(`${api}/sandbox/mail/${mail.id}/attachment/0`)).status, 401);
const activate = () => fetch(`${api}/license/activate`, { method: 'POST', body: JSON.stringify({ key, device_id: nonce, device_name: 'Hosted sandbox check' }) });
assert.equal((await activate()).status, 200);
const active = async id => (await fetch(`${api}/license/status?id=${id}`)).json();
await event('charge.dispute.created', { payment_intent: first.payment_intent, status: 'needs_response' });
assert.equal((await active(payload.id)).active, true);
await event('charge.dispute.closed', { payment_intent: first.payment_intent, status: 'lost' });
assert.equal((await active(payload.id)).active, false);
assert.equal((await activate()).status, 403);
const key2 = keyFrom(current.find(m => m.text.includes(second.id)));
const id2 = JSON.parse(Buffer.from(key2.split('.')[0], 'base64url').toString()).id;
await event('charge.refunded', { payment_intent: second.payment_intent, refunded: false });
assert.equal((await active(id2)).active, true);
await event('charge.refunded', { payment_intent: second.payment_intent, refunded: true });
assert.equal((await active(id2)).active, false);
const id = randomUUID();
const withdrawal = { name: 'Sandbox deployment check', contract_reference: first.id, email: 'deployment-check@example.invalid', locale: 'de' };
const submit = () => fetch(`${api}/withdrawal`, { method: 'POST', headers: { Origin: api, 'Content-Type': 'application/json', 'Idempotency-Key': id }, body: JSON.stringify(withdrawal) });
const response = await submit();
assert.equal(response.status, 202);
const receipt = await response.json();
const duplicate = await submit();
assert.equal(duplicate.status, 202);
assert.deepEqual(await duplicate.json(), receipt);
messages = await inbox();
assert.equal(messages.length, Math.min(30, before.length + 4));
const receipts = messages.filter(m => m.text.includes(id));
assert.equal(receipts.length, 2);
assert.ok(receipts.some(m => m.to.includes('support@trainvent.com')));
assert.ok(receipts.some(m => m.to.includes(withdrawal.email)));
assert.ok(receipts.every(m => m.text.includes(new Date(receipt.received_at * 1000).toISOString())));
writeFileSync(`${directory}/acceptance.json`, JSON.stringify({ checked_at: new Date().toISOString(), synthetic: true, checkout_sessions: [first.id, second.id], withdrawal: id, capture_count: 4, pdf_hashes_match: true }), { mode: 0o600 });
console.log('Hosted sandbox passed: TEST site/noindex, private inbox, signed test events only, duplicate-safe key delivery, four PDF hashes, sandbox signature/activation, dispute/refund revocation and customer/support withdrawal receipts. Synthetic events only; no real payment or external email.');
